const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '../studynest_fe');
const ts = require(path.join(root, 'node_modules/typescript'));
const moduleRef = { exports: {} };
const code = ts.transpileModule(fs.readFileSync(path.join(root, 'src/stores/notifications.ts'), 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
vm.runInNewContext(code, { module: moduleRef, exports: moduleRef.exports, require: name => require(path.join(root, 'node_modules', name)), console });
const store = moduleRef.exports.useRealtimeNotiStore;
const notification = id => ({ id, title: 'Thông báo đơn vị', type: 'provider', is_read: false });
store.getState().init('LECTURER', 'teacher-1');
store.getState().hydrate('LECTURER', [], 0);
assert.equal(store.getState().latestLiveNotification, null);
store.getState().add('LECTURER', notification('first'));
assert.equal(store.getState().latestLiveNotification.notification.id, 'first', 'The first event in an empty inbox must reach the toast listener');
assert.equal(store.getState().buckets.LECTURER.unread, 1);
const live = store.getState().latestLiveNotification;
store.getState().add('LECTURER', notification('first'));
assert.equal(store.getState().latestLiveNotification, live, 'Duplicate deliveries must not replay toasts');
assert.equal(store.getState().buckets.LECTURER.unread, 1);
store.getState().hydrate('LECTURER', [notification('historic'), notification('first')], 2);
assert.equal(store.getState().latestLiveNotification, live, 'Hydrating history must not emit live toast events');
store.getState().clearAll();
assert.equal(store.getState().latestLiveNotification, null);
store.getState().init('ADMIN', 'admin-1');
assert.equal(store.getState().buckets.LECTURER, undefined, 'Account switches must clear the previous inbox');
console.log('PASS: first provider event, duplicate delivery, history hydration and account isolation');
